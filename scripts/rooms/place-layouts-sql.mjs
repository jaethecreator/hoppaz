// The SQL text of supabase/place_room_layouts.sql, built from the room data. Imported by export-place-layouts.mjs (which
// writes the file) and by check-campaign.mjs (which fails when the file on disk is not exactly this).
import { loadCampaign } from "./load-campaign.mjs";

const q = (text) => `'${String(text).replaceAll("'", "''")}'`;

export function placeLayoutsSql() {
  const { PLACE_ROOMS, sceneBlocks } = loadCampaign();
  const rows = PLACE_ROOMS.map((room) => {
    const l = room.layout;
    const data = {
      grid: l.grid,
      spawn: l.spawn,
      zones: l.zones,
      privateAreas: l.privateAreas,
      blocks: sceneBlocks(l),
      // Props by id, so a later server call (Game Time hiding places, the exit) can find them without the app's code.
      props: l.props.map((p) => ({ id: p.id, kind: p.kind, x: p.x, y: p.y, w: p.w, h: p.h, solid: !!p.solid })),
    };
    return `  (${q(room.key)}, ${q(room.kind)}, ${room.slug ? q(room.slug) : "null"}, ${q(JSON.stringify(data))}::jsonb)`;
  });

  return `-- Hoppaz: walkable grids of the event and hotspot rooms (src/lib/campaign/rooms/*), generated by
-- scripts/rooms/export-place-layouts.mjs. Do not edit by hand.
--
-- NOT part of crew_rooms.sql and not loaded by anything yet: it is a separate table on purpose, so a crew can never be
-- pointed at one of these rooms (crew_rooms.template has a foreign key to crew_room_layouts only). The walking server
-- for hotspot rooms (hotspot_rooms.sql, Ola) reads from here. Same data shape as crew_room_layouts.data, plus the props.
-- Safe to run twice.

create table if not exists public.place_room_layouts (
  template text primary key,
  kind     text not null check (kind in ('event', 'hotspot')),
  slug     text,
  data     jsonb not null
);

alter table public.place_room_layouts enable row level security;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'place_room_layouts' and policyname = 'place_room_layouts_read') then
    create policy place_room_layouts_read on public.place_room_layouts for select to anon, authenticated using (true);
  end if;
end $$;
revoke insert, update, delete on public.place_room_layouts from anon, authenticated;

-- LAYOUT_SEED
insert into public.place_room_layouts(template, kind, slug, data) values
${rows.join(",\n")}
on conflict (template) do update set kind = excluded.kind, slug = excluded.slug, data = excluded.data;
`;
}
