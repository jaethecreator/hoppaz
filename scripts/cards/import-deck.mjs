#!/usr/bin/env node
/**
 * Turns a deck file (JSON) into SQL that loads it: card_sets and cards upserted by
 * key, so running it again updates a card's words, point or status and never
 * touches what has been handed out (copies_issued, anyone's copies or album).
 *
 *   node scripts/cards/import-deck.mjs scripts/cards/deck.sample.json > supabase/cards_sample.sql
 *
 * Then run the SQL in the Supabase SQL editor, after cards.sql. The database
 * refuses a card whose point is in a no-spawn zone (give it a public viewpoint
 * instead) and a live card that is not signed off.
 *
 * The deck file:
 *   { "sets":  [{ "key", "name", "title", "kind": "council|city|campus", "live" }],
 *     "cards": [{ "key", "set", "name", "fact", "fact_source", "tier": "common|rare|epic|legendary",
 *                 "lat", "lng", "radius_m"?, "lore"?, "known_for"?, "question"?, "visit_tip"?,
 *                 "tier_reason"?, "founders_call"?, "person"?, "weight"?, "copies_total"?,
 *                 "art_kind"?, "art_credit"?, "status"? (draft), "signed_off"?, "sensitive"?, "campaign_hold"? }],
 *     "note"?: "a line for the top of the SQL" }
 *
 * copies_total defaults by tier: Legendary 10, Epic 100, Rare 1,000, Common none.
 * Points must be in Lagos (lat 6.30 to 6.80, lng 3.05 to 3.95).
 */
import { readFileSync } from "node:fs";

const COPIES = { common: null, rare: 1000, epic: 100, legendary: 10 };
const KINDS = ["council", "city", "campus"];
const ART = ["map", "generated", "photo", "owned"];

const file = process.argv[2];
if (!file) {
  console.error("Usage: node scripts/cards/import-deck.mjs <deck.json>");
  process.exit(1);
}
const deck = JSON.parse(readFileSync(file, "utf8"));
const problems = [];
const say = (where, what) => problems.push(`${where}: ${what}`);

const q = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const b = (v) => (v ? "true" : "false");
const len = (where, field, v, lo, hi, required) => {
  if (v === undefined || v === null || v === "") {
    if (required) say(where, `${field} is required`);
    return;
  }
  if (typeof v !== "string" || v.length < lo || v.length > hi) say(where, `${field} needs ${lo} to ${hi} characters`);
};

const sets = Array.isArray(deck.sets) ? deck.sets : [];
const cards = Array.isArray(deck.cards) ? deck.cards : [];
const setKeys = new Set();
for (const s of sets) {
  const w = `set ${s.key ?? "?"}`;
  if (!/^[a-z0-9][a-z0-9-]{1,59}$/.test(s.key ?? "")) say(w, "key must be lower-case letters, digits and dashes");
  if (setKeys.has(s.key)) say(w, "appears twice");
  setKeys.add(s.key);
  len(w, "name", s.name, 2, 80, true);
  len(w, "title", s.title, 2, 60, true);
  if (!KINDS.includes(s.kind)) say(w, `kind must be ${KINDS.join(", ")}`);
}
const cardKeys = new Set();
for (const c of cards) {
  const w = `card ${c.key ?? "?"}`;
  if (!/^[a-z0-9][a-z0-9-]{1,79}$/.test(c.key ?? "")) say(w, "key must be lower-case letters, digits and dashes");
  if (cardKeys.has(c.key)) say(w, "appears twice");
  cardKeys.add(c.key);
  if (!setKeys.has(c.set)) say(w, `set ${c.set} is not in this file`);
  len(w, "name", c.name, 2, 60, true);
  len(w, "fact", c.fact, 10, 400, true);
  len(w, "fact_source", c.fact_source, 4, 400, true);
  len(w, "lore", c.lore, 1, 300, false);
  len(w, "known_for", c.known_for, 1, 200, false);
  len(w, "question", c.question, 1, 200, false);
  len(w, "visit_tip", c.visit_tip, 1, 200, false);
  len(w, "tier_reason", c.tier_reason, 1, 200, false);
  if (!(c.tier in COPIES)) say(w, "tier must be common, rare, epic or legendary");
  if (!(typeof c.lat === "number" && c.lat >= 6.3 && c.lat <= 6.8 && typeof c.lng === "number" && c.lng >= 3.05 && c.lng <= 3.95)) say(w, "lat and lng must be a point in Lagos");
  if (c.radius_m !== undefined && !(Number.isInteger(c.radius_m) && c.radius_m >= 25 && c.radius_m <= 500)) say(w, "radius_m is 25 to 500");
  if (c.art_kind !== undefined && !ART.includes(c.art_kind)) say(w, `art_kind must be ${ART.join(", ")}`);
  if (c.status === "live" && !c.signed_off) say(w, "a live card must be signed off");
  if (c.tier === "common" && c.copies_total) say(w, "a Common has no copy limit");
}
if (problems.length) {
  console.error(`${problems.length} problem(s) in ${file}:\n  ${problems.join("\n  ")}`);
  process.exit(1);
}

const out = [];
out.push("-- ============================================================================");
out.push(`-- Generated by scripts/cards/import-deck.mjs from ${file}. Do not edit by hand:`);
out.push("-- change the deck file and generate again. Run after cards.sql. Safe to run again.");
if (deck.note) for (const line of String(deck.note).split("\n")) out.push(`-- ${line}`);
out.push("-- ============================================================================");
out.push("begin;");
for (const s of sets) {
  out.push(
    `insert into public.card_sets (key, name, title, kind, live) values (${q(s.key)}, ${q(s.name)}, ${q(s.title)}, ${q(s.kind)}, ${b(s.live)})\n` +
      `on conflict (key) do update set name = excluded.name, title = excluded.title, kind = excluded.kind, live = excluded.live;`
  );
}
for (const c of cards) {
  const copies = c.copies_total ?? COPIES[c.tier];
  const cols = {
    key: q(c.key),
    set_id: `(select id from public.card_sets where key = ${q(c.set)})`,
    person: b(c.person),
    name: q(c.name),
    fact: q(c.fact),
    fact_source: q(c.fact_source),
    lore: q(c.lore),
    known_for: q(c.known_for),
    question: q(c.question),
    visit_tip: q(c.visit_tip),
    tier: q(c.tier),
    tier_reason: q(c.tier_reason),
    founders_call: b(c.founders_call),
    geog: `st_point(${c.lng}, ${c.lat})::geography`,
    radius_m: String(c.radius_m ?? 150),
    weight: String(c.weight ?? 1),
    copies_total: copies === null ? "null" : String(copies),
    art_kind: q(c.art_kind ?? "map"),
    art_credit: q(c.art_credit),
    status: q(c.status ?? "draft"),
    signed_off: b(c.signed_off),
    sensitive: b(c.sensitive),
    campaign_hold: b(c.campaign_hold),
  };
  const names = Object.keys(cols);
  const update = names.filter((n) => n !== "key").map((n) => `${n} = excluded.${n}`).join(", ");
  out.push(
    `insert into public.cards (${names.join(", ")})\nvalues (${names.map((n) => cols[n]).join(", ")})\n` +
      `on conflict (key) do update set ${update};`
  );
}
out.push("commit;");
process.stdout.write(out.join("\n") + "\n");
console.error(`${sets.length} set(s), ${cards.length} card(s).`);
